-- Adição isolada do planejamento de mesas e convidados.
-- Não altera nem remove nenhuma tabela ou registro existente do CRM.
begin;

create table if not exists public.wedding_tables (
  id bigint generated by default as identity primary key,
  name text not null,
  color text not null default '#dcefe0',
  capacity integer not null default 10 check (capacity > 0 and capacity <= 1000),
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.wedding_guests (
  id bigint generated by default as identity primary key,
  full_name text not null,
  household text not null default '',
  rsvp_status text not null default 'pendente'
    check (rsvp_status in ('confirmado', 'pendente', 'recusado')),
  table_id bigint null references public.wedding_tables(id) on delete set null,
  notes text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists idx_wedding_guests_table_id
  on public.wedding_guests(table_id);
create index if not exists idx_wedding_guests_full_name
  on public.wedding_guests(lower(full_name));

alter table public.wedding_tables enable row level security;
alter table public.wedding_guests enable row level security;

drop policy if exists "public_link_manage_wedding_tables" on public.wedding_tables;
create policy "public_link_manage_wedding_tables"
  on public.wedding_tables for all to anon, authenticated
  using (true) with check (true);

drop policy if exists "public_link_manage_wedding_guests" on public.wedding_guests;
create policy "public_link_manage_wedding_guests"
  on public.wedding_guests for all to anon, authenticated
  using (true) with check (true);

grant select, insert, update, delete on public.wedding_tables to anon, authenticated;
grant select, insert, update, delete on public.wedding_guests to anon, authenticated;
grant usage, select on all sequences in schema public to anon, authenticated;

commit;